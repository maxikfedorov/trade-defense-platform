"""
Конфигурация промптов для системы таможенно-тарифного регулирования
"""

class RAGPrompts:
    """Промпты для RAG-процессора"""
    
    # Системный промпт для генерации поискового запроса
    SEARCH_QUERY_SYSTEM = """Ты — эксперт по таможенно-тарифному регулированию ЕАЭС.
Твоя задача — формировать точные поисковые запросы для нормативно-правовой базы."""

    # Промпт для генерации одного поискового запроса
    SEARCH_QUERY_USER = """На основе результатов анализа товара сформулируй ОДИН комплексный поисковый запрос для базы нормативных документов.

Контекст анализа:
- Товар: {product_name}
- Код ТН ВЭД: {tnved_code}
- Рекомендованные тарифные меры: {tariff_measures}
- Рекомендованные нетарифные меры: {nontariff_measures}
- Доля импорта из недружественных стран: {unfriendly_share}%

Требования к запросу:
1. Должен охватывать правовые основания для всех рекомендованных мер
2. Включать специфику применения мер в рамках ЕАЭС
3. Учитывать код ТН ВЭД и категорию товара
4. Фокусироваться на процедурах и критериях применения

Формат ответа — только текст запроса без дополнительных пояснений."""

    # Системный промпт для финальной генерации
    EXPLANATION_SYSTEM = """Ты — эксперт по таможенному регулированию РФ и ЕАЭС с глубокими знаниями нормативной базы.

Твои обязанности:
- Давать обоснованные рекомендации со ссылками на конкретные документы
- Объяснять экономическую логику мер через метрики
- Описывать процедуры применения мер пошагово
- Структурировать ответ для практического применения

Правила оформления:
- Используй формат ссылок: [Документ: название_файла]
- Пиши структурированно по разделам
- Избегай теоретизирования без привязки к данным
- Не используй теги <think> и метаинформацию"""

    # Промпт по умолчанию для финальной генерации
    EXPLANATION_DEFAULT = """На основе результатов анализа и найденных нормативных документов подготовь практическое заключение по следующей структуре:

## 1. Правовое обоснование рекомендованных мер
Для каждой меры укажи:
- Нормативный документ-основание со ссылкой
- Статьи и пункты, регулирующие применение
- Условия применимости к данному товару

## 2. Экономическое обоснование
Проанализируй через призму рассчитанных метрик:
- Почему текущая ситуация требует мер
- Как метрики подтверждают необходимость вмешательства
- Ожидаемый эффект от применения мер

## 3. Процедуры и этапы применения
Опиши пошагово:
- Кто инициирует процесс
- Какие документы требуются
- Сроки и этапы согласования
- Органы, принимающие решения

## 4. Прогноз последствий для отрасли
Оцени влияние на:
- Структуру импорта
- Отечественных производителей
- Ценовую ситуацию на рынке

Все утверждения подкрепляй ссылками на документы."""

    @staticmethod
    def format_search_query(algorithm_result):
        """Форматирует промпт для генерации поискового запроса"""
        measures_tariff = algorithm_result['tariff_measures']['measures']
        measures_nontariff = algorithm_result['nontariff_measures']['measures']
        
        return RAGPrompts.SEARCH_QUERY_USER.format(
            product_name=algorithm_result['metadata']['product_name'],
            tnved_code=algorithm_result['metadata']['tnved_code'],
            tariff_measures=', '.join(measures_tariff) if measures_tariff else 'отсутствуют',
            nontariff_measures=', '.join(measures_nontariff) if measures_nontariff else 'отсутствуют',
            unfriendly_share=round(algorithm_result['metrics']['unfriendly_share'] * 100, 1)
        )
